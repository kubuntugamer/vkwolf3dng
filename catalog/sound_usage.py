#!/usr/bin/env python3
"""Map each Wolf3D sound enum symbol to its code reference sites.

Reads the sound enums from WOLFSRC/AUDIO*.H and scans WOLFSRC/*.C, reporting
(file, line, enclosing function/table) for every whole-word reference. Writes
Markdown to `sound-references.md` (stdout when `-` is passed). Context is
derived with a definition-line heuristic: a column-0 line whose last
identifier precedes an opening paren starts a function; a column-0 line that
defines a global array (`name[] = ...`, e.g. `wolfdigimap[]`) starts a
file-scope table.
"""
import os
import re

HERE = os.path.dirname(__file__)
SRC = os.path.join(HERE, "..", "WOLFSRC")

AUDIO_HEADERS = ["AUDIOWL6.H", "AUDIOSOD.H"]
SOUND_ENTRY = re.compile(r"^\s*([A-Za-z_]\w*)\s*,?\s*(?://.*)?$")
STOP = {"ENUMEND", "LASTSOUND", "LASTMUSIC"}

# token immediately before '(' on a column-0 line is assumed to be a function name
FUNC_DEF = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*\(|^.*?[>*\s]([A-Za-z_][A-Za-z0-9_]*)\s*\($")
CONTROL = {
    "if", "for", "while", "switch", "return", "do", "else", "sizeof",
    "defined", "typedef", "struct", "union", "enum",
}


def load_sound_names():
    names = []
    for fn in AUDIO_HEADERS:
        path = os.path.join(SRC, fn)
        if not os.path.exists(path):
            continue
        with open(path, errors="replace") as fh:
            for raw in fh:
                low = raw.lower()
                if "music names" in low:
                    break  # sound enum comes first; stop at music section
                line = raw.strip()
                if not line or line.startswith(("//", "#")) or line.startswith("}"):
                    continue
                m = SOUND_ENTRY.match(raw)
                if not m:
                    continue
                sym = m.group(1)
                if sym in STOP:
                    continue
                if sym not in names:
                    names.append(sym)
    return names


def c_sources():
    return sorted(
        os.path.join(SRC, f) for f in os.listdir(SRC) if f.endswith(".C")
    )


def build_function_map(path):
    """Return list of (lineno, label) for function defs and global arrays."""
    funcs = []
    with open(path, errors="replace") as fh:
        for i, raw in enumerate(fh, 1):
            if not raw or raw[0] in " \t#/*}":
                continue
            line = raw.rstrip("\n")
            # global array definition, e.g.  static char wolfdigimap[] = {
            if "[" in line and "]" in line and "=" in line and "(" not in line:
                name = re.match(r"[^=]*?([A-Za-z_]\w*)\s*\[", line)
                if name:
                    funcs.append((i, f"{name.group(1)}[]"))
                continue
            if line.endswith(";") or "=" in line.split("(")[0]:
                continue
            # candidate name = last identifier before first '('
            idx = line.find("(")
            if idx < 0:
                continue
            before = line[:idx]
            ids = re.findall(r"[A-Za-z_]\w*", before)
            if not ids:
                continue
            name = ids[-1]
            if name in CONTROL:
                continue
            funcs.append((i, name))
    return funcs


def enclosing(funcs, lineno):
    cur = "?"
    for ln, name in funcs:
        if ln > lineno:
            break
        cur = name
    return cur


def main():
    import sys

    names = load_sound_names()
    files = c_sources()
    fmap = {f: build_function_map(f) for f in files}

    patterns = {n: re.compile(r"\b" + re.escape(n) + r"\b") for n in names}
    refs = {n: [] for n in names}

    for path in files:
        base = os.path.basename(path)
        with open(path, errors="replace") as fh:
            for i, raw in enumerate(fh, 1):
                for n, pat in patterns.items():
                    if pat.search(raw):
                        func = enclosing(fmap[path], i)
                        refs[n].append((base, i, func))

    out = [
        "<!-- Generated by catalog/sound_usage.py; do not edit by hand. -->",
        "",
        "# Sound reference index (raw)",
        "",
        "Every whole-word reference to a sound-enum symbol in `WOLFSRC/*.C`,",
        "with the enclosing function or file-scope table.",
        "",
        "| Sound | References (file:line, context) |",
        "| --- | --- |",
    ]
    for n in names:
        if refs[n]:
            locs = "<br>".join(f"`{f}:{l}` {fn}" for f, l, fn in refs[n])
        else:
            locs = "_(unreferenced in source)_"
        out.append(f"| `{n}` | {locs} |")
    out.append("")

    text = "\n".join(out)
    if len(sys.argv) > 1 and sys.argv[1] == "-":
        sys.stdout.write(text)
    else:
        dest = os.path.join(HERE, "sound-references.md")
        with open(dest, "w") as fh:
            fh.write(text)
        sys.stdout.write(f"wrote {dest} ({len(names)} sounds)\n")


if __name__ == "__main__":
    main()
